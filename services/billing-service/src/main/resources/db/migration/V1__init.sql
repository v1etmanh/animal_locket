CREATE TABLE products (
    sku VARCHAR(60) NOT NULL,
    type VARCHAR(14) NOT NULL,
    item VARCHAR(40) NOT NULL,
    quantity INTEGER NOT NULL,
    active BOOLEAN NOT NULL,
    PRIMARY KEY (sku)
);

CREATE TABLE purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    store VARCHAR(10) NOT NULL,
    store_transaction_id VARCHAR(100) NOT NULL,
    original_transaction_id VARCHAR(100),
    public_id VARCHAR(20) NOT NULL,
    sku VARCHAR(60) NOT NULL,
    status VARCHAR(10) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_purchase_store_tx UNIQUE (store, store_transaction_id)
);
CREATE INDEX idx_purchase_user ON purchases (public_id);

CREATE TABLE subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id VARCHAR(20) NOT NULL,
    sku VARCHAR(60) NOT NULL,
    store VARCHAR(10) NOT NULL,
    original_transaction_id VARCHAR(100) NOT NULL,
    status VARCHAR(10) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_sub_store_orig UNIQUE (store, original_transaction_id)
);
CREATE INDEX idx_sub_user ON subscriptions (public_id);
CREATE INDEX idx_sub_status_exp ON subscriptions (status, expires_at);

CREATE TABLE wallet_balances (
    public_id VARCHAR(20) NOT NULL,
    item VARCHAR(40) NOT NULL,
    balance INTEGER NOT NULL,
    PRIMARY KEY (public_id, item),
    CONSTRAINT ck_wallet_non_negative CHECK (balance >= 0)
);

CREATE TABLE wallet_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id VARCHAR(20) NOT NULL,
    item VARCHAR(40) NOT NULL,
    delta INTEGER NOT NULL,
    reason VARCHAR(12) NOT NULL,
    ref VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_ledger_ref UNIQUE (reason, ref, item)
);
CREATE INDEX idx_ledger_user ON wallet_ledger (public_id, created_at);

CREATE TABLE webhook_events (
    id VARCHAR(100) NOT NULL,
    store VARCHAR(10) NOT NULL,
    type VARCHAR(60),
    received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE outbox_events (
    id VARCHAR(36) NOT NULL,
    topic VARCHAR(100) NOT NULL,
    event_key VARCHAR(100) NOT NULL,
    type VARCHAR(60) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id)
);
CREATE INDEX idx_outbox_unpublished ON outbox_events (published_at, created_at);

CREATE TABLE processed_events (
    event_id VARCHAR(36) NOT NULL,
    processed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (event_id)
);

