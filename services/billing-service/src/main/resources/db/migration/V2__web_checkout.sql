-- Phiên thanh toán web: app xin một mã dùng một lần (lưu băm SHA-256), gắn với publicId + sku + số tiền chốt lúc tạo.
CREATE TABLE checkout_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    token_hash VARCHAR(64) NOT NULL,
    public_id VARCHAR(20) NOT NULL,
    sku VARCHAR(60) NOT NULL,
    amount_cents INTEGER NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(12) NOT NULL,
    paypal_order_id VARCHAR(64),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_checkout_token UNIQUE (token_hash)
);
CREATE INDEX idx_checkout_user ON checkout_sessions (public_id);
